"""Generate native rounded backgrounds; corner radii stay circular after resize."""
from pathlib import Path

project=Path(__file__).resolve().parent.parent
res=project/'android/app/src/main/res/drawable'
java=project/'android/app/src/main/java/com/shiguang/focus/HeatmapTiles.java'
alpha=[0,51,97,148,199,255]
def color(level,dark):
    if level==0:return '#2a2f39' if dark else '#efedf0'
    fg=0x409aff if dark else 0x087dff
    bg=0x20242c if dark else 0xfffcfd
    a=alpha[level]
    value=sum((((fg>>s&255)*a+(bg>>s&255)*(255-a)+127)//255)<<s for s in [0,8,16])
    return f'#{value:06x}'
groups=[]
for compact in [False,True]:
    for dark in [False,True]:
        for today in [False,True]:
            refs=[]
            for level in range(6):
                name=f'widget_day_{"compact" if compact else "normal"}_{"dark" if dark else "light"}_{"today" if today else "plain"}_{level}'
                stroke=f'<stroke android:width="1.2dp" android:color="{"#409aff" if dark else "#087dff"}"/>' if today else ''
                (res/(name+'.xml')).write_text(f'<shape xmlns:android="http://schemas.android.com/apk/res/android"><solid android:color="{color(level,dark)}"/><corners android:radius="{3 if compact else 4}dp"/>{stroke}</shape>\n',encoding='utf-8')
                refs.append('R.drawable.'+name)
            groups.append('        {'+', '.join(refs)+'}')
java.write_text('''package com.shiguang.focus;

/** Generated by tool/generate_widget_shapes.py; explicit IDs survive shrinking. */
final class HeatmapTiles {
    private static final int[][] BACKGROUNDS = {
'''+',\n'.join(groups)+'''
    };
    static int background(int level, boolean dark, boolean today, boolean compact) {
        return BACKGROUNDS[(compact ? 4 : 0) + (dark ? 2 : 0) + (today ? 1 : 0)][level];
    }
}
''',encoding='utf-8')
print('Generated 48 size-independent rounded backgrounds and native lookup.')
